"""
pcap_manager.py — PCAP and PCAPNG file management.

Handles loading, validating, and exporting PCAP/PCAPNG captures safely.
Converts collections of Scapy packets and parsed packet dictionaries into
Pandas DataFrames for tabular analysis and visualization.
"""

from __future__ import annotations

import os
import logging
from typing import Tuple, List, Dict, Any, Optional
import pandas as pd
from scapy.all import rdpcap, wrpcap, Packet

from core.packet_parser import parse_packet

logger = logging.getLogger(__name__)


def validate_pcap_path(filepath: str) -> Tuple[bool, Optional[str]]:
    """
    Validate that a given path exists and is likely a readable capture file.

    Returns:
        (is_valid, error_message)
    """
    if not filepath:
        return False, "File path is empty."

    if not os.path.exists(filepath):
        return False, f"File not found: {filepath}"

    if not os.path.isfile(filepath):
        return False, f"Path is not a regular file: {filepath}"

    if os.path.getsize(filepath) == 0:
        return False, "Capture file is empty (0 bytes)."

    return True, None


def load_pcap(filepath: str) -> Tuple[List[Packet], List[Dict[str, Any]], Optional[str]]:
    """
    Read a PCAP or PCAPNG file and parse all contained packets.

    Args:
        filepath: Path to the capture file.

    Returns:
        Tuple of:
          - raw_packets: List of Scapy Packet objects.
          - parsed_packets: List of normalized dictionaries generated by parse_packet.
          - error_message: None if successful, or description of failure.
    """
    is_valid, err = validate_pcap_path(filepath)
    if not is_valid:
        return [], [], err

    try:
        raw_packets = list(rdpcap(filepath))
    except Exception as e:
        try:
            from scapy.utils import PcapNgReader
            with PcapNgReader(filepath) as reader:
                raw_packets = list(reader)
        except Exception:
            import gc
            gc.collect()
            logger.error(f"Failed to read PCAP file '{filepath}': {e}")
            return [], [], f"Corrupt or unsupported capture file format: {e}"

    if not raw_packets:
        return [], [], "Capture file contains 0 packets."

    parsed_packets = []
    for idx, pkt in enumerate(raw_packets, start=1):
        parsed = parse_packet(pkt, packet_num=idx)
        parsed_packets.append(parsed)

    return raw_packets, parsed_packets, None


def export_pcap(packets: List[Packet], filepath: str) -> Tuple[bool, Optional[str]]:
    """
    Write a list of raw Scapy packets out to a PCAP file.

    Args:
        packets: List of Scapy Packet objects to export.
        filepath: Destination output path.

    Returns:
        (success, error_message)
    """
    if not packets:
        return False, "No packets provided to export."

    try:
        dirname = os.path.dirname(filepath)
        if dirname:
            os.makedirs(dirname, exist_ok=True)
        wrpcap(filepath, packets)
        return True, None
    except Exception as e:
        logger.error(f"Failed to write PCAP file '{filepath}': {e}")
        return False, f"Failed to save PCAP file: {e}"


def packets_to_dataframe(parsed_packets: List[Dict[str, Any]]) -> pd.DataFrame:
    """
    Convert a list of parsed packet dictionaries into a clean Pandas DataFrame.

    Ensures standard datatypes and column definitions for easy UI display
    and filtering in Streamlit.
    """
    if not parsed_packets:
        return pd.DataFrame()

    df = pd.DataFrame(parsed_packets)

    # Convert timestamps to float if needed
    if "timestamp" in df.columns:
        df["timestamp"] = pd.to_numeric(df["timestamp"], errors="coerce")

    # Fill NA for categorical/text columns with sensible defaults
    text_cols = ["src_ip", "dst_ip", "protocol", "info", "tcp_flags_str"]
    for col in text_cols:
        if col in df.columns:
            df[col] = df[col].fillna("—")

    # Format ports cleanly without '.0' float artifacts
    for pcol in ["src_port", "dst_port"]:
        if pcol in df.columns:
            df[pcol] = df[pcol].apply(
                lambda p: str(int(float(p))) if pd.notna(p) and str(p) != "—" and str(p).replace('.', '', 1).isdigit() else "—"
            )

    return df
